fn py_face_provider_enriches_pyi() {
    let _g = PY_FACE_TEST.lock().unwrap();
    unsafe extern "C" fn provider(
        _ctx: *mut c_void,
        fqn: *const u8,
        fqn_len: u32,
        buf: *mut u8,
        inout_len: *mut u32,
    ) -> i32 {
        let fqn = unsafe { core::str::from_utf8_unchecked(core::slice::from_raw_parts(fqn, fqn_len as usize)) };
        let text = emit_init_pyi_names(fqn, &["run", "diff"]);
        if buf.is_null() {
            unsafe { *inout_len = text.len() as u32 };
            return 1;
        }
        let n = core::cmp::min(text.len(), unsafe { *inout_len } as usize);
        unsafe {
            core::ptr::copy_nonoverlapping(text.as_ptr(), buf, n);
            *inout_len = n as u32;
        }
        1
    }
    assert!(unsafe {
        register_fn(
            "test.gen_pyi",
            "noop",
            0xa as *mut c_void,
            "void(void)",
        )
    });
    unsafe {
        pm_util_gen_set_py_face_provider(Some(provider), core::ptr::null_mut());
    }
    let faces = faces_for_fqn("test.gen_pyi").unwrap();
    let pyi = &faces.iter().find(|(n, _)| n == FACE_INIT_PYI).unwrap().1;
    assert!(pyi.contains("def run("));
    assert!(pyi.contains("def diff("));
    unsafe {
        pm_util_gen_set_py_face_provider(None, core::ptr::null_mut());
    }
}

